/// One scripted action: `seconds:command[:args]`, separated by `;` in `RL_SCRIPT`.
/// Commands: `move x,y`, `click x,y`, `rclick x,y`, `key vk`, `shot path`, `quit`.
struct Step {
    at: f64,
    cmd: String,
    arg: String,
}

fn parse_script(s: &str) -> Vec<Step> {
    let mut v: Vec<Step> = s
        .split(';')
        .filter_map(|item| {
            let mut p = item.trim().splitn(3, ':');
            Some(Step { at: p.next()?.parse().ok()?, cmd: p.next()?.to_string(), arg: p.next().unwrap_or("").to_string() })
        })
        .collect();
    // Clicks and key presses are held for a while: the game polls button state per frame.
    let mut extra = Vec::new();
    for st in &v {
        match st.cmd.as_str() {
            "click" | "rclick" | "dclick" => extra.push(Step { at: st.at + 0.25, cmd: format!("{}up", &st.cmd[..st.cmd.len() - 5]), arg: st.arg.clone() }),
            "key" => extra.push(Step { at: st.at + 0.2, cmd: "keyup".into(), arg: st.arg.clone() }),
            _ => {}
        }
    }
    v.extend(extra);
    v.sort_by(|a, b| a.at.total_cmp(&b.at));
    v
}

fn xy(arg: &str) -> (i32, i32) {
    let (x, y) = arg.split_once(',').unwrap_or(("0", "0"));
    (x.trim().parse().unwrap_or(0), y.trim().parse().unwrap_or(0))
}

fn run_script_step(m: &mut machine::Machine, st: &Step) -> bool {
    let uc = &mut m.uc;
    match st.cmd.as_str() {
        "move" => {
            let (x, y) = xy(&st.arg);
            if std::env::var_os("RL_LOG_MOVE").is_some() {
                eprintln!("[move] {x},{y}");
            }
            frontend::inject_mouse(uc, x, y, None);
        }
        "click" | "rclick" | "dclick" => {
            let (x, y) = xy(&st.arg);
            frontend::inject_mouse(uc, x, y, None);
            frontend::inject_mouse_msg(uc, x, y, Some((st.cmd == "rclick", true)), st.cmd == "dclick");
        }
        // The "up" halves are generated by `parse_script` (e.g. "clickup" is `click` + "up").
        c if c.ends_with("up") && c != "keyup" => {
            let (x, y) = xy(&st.arg);
            frontend::inject_mouse(uc, x, y, Some((c.starts_with('r'), false)));
        }
        "key" => {
            let vk: u8 = st.arg.trim().parse().unwrap_or(0);
            frontend::inject_key(uc, vk, true);
        }
        "keyup" => {
            let vk: u8 = st.arg.trim().parse().unwrap_or(0);
            frontend::inject_key(uc, vk, false);
        }
        "shot" => dump(m, Some(&st.arg)),
        // Debug: hex dump of guest memory, arg `addr:len` (hex).
        "mem" => {
            if let Some((a, l)) = st.arg.split_once(':') {
                let (a, l) = (u32::from_str_radix(a, 16).unwrap_or(0), usize::from_str_radix(l, 16).unwrap_or(0));
                eprintln!("[mem {a:x}] {:02x?}", machine::rd_bytes(uc, a, l));
            }
        }
        // Debug: list the building table (index, +1, +2, +8, +0x72, +0x7c, +0xab).
        "bld" => {
            let base = machine::rd32(uc, 0x4e19a0);
            eprintln!("[bld] base={base:#x} blds={:#x}", machine::rd32(uc, 0x4e19a4));
            for i in 0..800u32 {
                let b = machine::rd_bytes(uc, base + i * 0x114, 0x114);
                if b[2] != 0 {
                    if i == 0 {
                        eprintln!("[bld0] {:02x?}", b);
                    }
                    eprintln!("[bld] {i} own={} t1={:#x} t2={:#x} p8={} n0a={} cap0c={} list={:?} n70={} f72={:#x} p7c={} fab={:#x} p7e={}", b[0], b[1], b[2], u16::from_le_bytes([b[8], b[9]]), u16::from_le_bytes([b[0xa], b[0xb]]), u16::from_le_bytes([b[0xc], b[0xd]]), (0..4).map(|k| u16::from_le_bytes([b[0x10 + 2 * k], b[0x11 + 2 * k]])).collect::<Vec<_>>(), u16::from_le_bytes([b[0x70], b[0x71]]), b[0x72], u16::from_le_bytes([b[0x7c], b[0x7d]]), b[0xab], u16::from_le_bytes([b[0x7e], b[0x7f]]));
                }
            }
        }
        // Debug: `find a,b` lists guest addresses holding the u16/u32 value `a` with `b` within the next 16 bytes (decimal).
        "find" => {
            let (a, b) = xy(&st.arg);
            for (lo, hi) in uc.mem_regions().unwrap_or_default().iter().map(|r| (r.begin, r.end)) {
                let Ok(buf) = uc.mem_read_as_vec(lo, (hi - lo + 1) as usize) else { continue };
                for w in [2usize, 4] {
                    let g = |i: usize| (0..w).fold(0i64, |v, k| v | (buf[i + k] as i64) << (8 * k));
                    for i in (0..buf.len().saturating_sub(24)).step_by(w) {
                        if g(i) == a as i64 && (w..=16).step_by(w).any(|d| g(i + d) == b as i64) {
                            eprintln!("[find] u{} at {:#x}", w * 8, lo + i as u64);
                        }
                    }
                }
            }
        }
        // Debug console command (see debug.rs).
        "dbg" => eprintln!("[dbg] {}", debug::run(uc, &st.arg)),
        "quit" => return false,
        other => eprintln!("script: unknown command {other}"),
    }
    true
}

/// Where saved games and other writable files live.
fn userdir() -> PathBuf {
    if let Some(d) = env::var_os("RL_USERDIR") {
        return PathBuf::from(d);
    }
    let home = |rel: &str| env::var_os("HOME").map(|h| PathBuf::from(h).join(rel));
    let base = if cfg!(windows) {
        env::var_os("APPDATA").map(PathBuf::from)
    } else if cfg!(target_os = "macos") {
        home("Library/Application Support")
    } else {
        env::var_os("XDG_DATA_HOME").map(PathBuf::from).or_else(|| home(".local/share"))
    };
    base.unwrap_or_else(|| PathBuf::from(".")).join("rising-lands")
}

/// Debug helper: `rl-emu --avi movie.avi out_prefix first count` writes decoded frames as PNGs.
fn dump_avi(args: &[String]) -> ExitCode {
    let bytes = std::fs::read(&args[1]).expect("read avi");
    let avi = video::Avi::parse(&bytes).expect("parse avi");
    eprintln!("{}x{} {} frames rate {:?} audio {} samples {}ch {}Hz", avi.width, avi.height, avi.frames.len(), avi.rate, avi.audio.len(), avi.channels, avi.sample_rate);
    let (first, count): (usize, usize) = (args[3].parse().unwrap_or(0), args[4].parse().unwrap_or(1));
    let mut dec = video::Cinepak::new(avi.width, avi.height);
    for (i, f) in avi.frames.iter().enumerate().take(first + count) {
        dec.decode(f).expect("decode");
        if i >= first {
            let file = std::fs::File::create(format!("{}{i:04}.png", args[2])).expect("png");
            let mut enc = png::Encoder::new(std::io::BufWriter::new(file), avi.width as u32, avi.height as u32);
            enc.set_color(png::ColorType::Rgb);
            enc.set_depth(png::BitDepth::Eight);
            enc.write_header().and_then(|mut w| w.write_image_data(&dec.rgb)).expect("write");
        }
    }
    ExitCode::SUCCESS
}

fn main() -> ExitCode {
    let mut args: Vec<String> = env::args().skip(1).collect();
    // Prototyping flags: `--skip-intro` drops the movies, `--new-game` clicks through the menus into mission 1.
    let skip_intro = args.iter().any(|a| a == "--skip-intro" || a == "--new-game");
    // `--mission N` / `--map WORLD/MONDE05.ETA`: like `--new-game`, then jump to mission N.
    let mission: Option<u32> = args.iter().position(|a| a == "--mission" || a == "--map").and_then(|i| {
        let digits: String = args.get(i + 1)?.rsplit(['/', '\\']).next()?.to_ascii_lowercase().trim_start_matches("monde").chars().take_while(char::is_ascii_digit).collect();
        digits.parse().ok().filter(|n| (1..=25).contains(n))
    });
    let skip_intro = skip_intro || mission.is_some();
    let new_game = args.iter().any(|a| a == "--new-game") || mission.is_some();
    if let Some(i) = args.iter().position(|a| a == "--mission" || a == "--map") {
        args.drain(i..(i + 2).min(args.len()));
    }
    args.retain(|a| !a.starts_with("--") || a == "--avi");
    if args.first().map(String::as_str) == Some("--avi") && args.len() >= 5 {
        return dump_avi(&args);
    }
    // Default layout: the folder the disc was extracted to (see `rl-tool disc`).
    let disc = PathBuf::from(args.get(1).cloned().or_else(|| env::var("RL_DISC").ok()).unwrap_or_else(|| "original".into()));
    let install = PathBuf::from(args.first().cloned().or_else(|| env::var("RL_GAME").ok()).unwrap_or_else(|| disc.join("INSTALHD").to_string_lossy().into_owned()));
    if !install.join("RISING.EXE").exists() {
        eprintln!("usage: rl-emu [<INSTALHD dir> [<disc root dir>]]\n\nCannot find RISING.EXE in {}.\nExtract your disc first: rl-tool disc <image.bin> original", install.display());
        return ExitCode::from(2);
    }
    let mut m = match machine::Machine::new(&install.join("RISING.EXE"), &install, &disc, &userdir()) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    };
    if let Ok(h) = std::fs::read_to_string(userdir().join("lasthost.txt")) {
        m.uc.get_data_mut().ui.last_host = h.trim().to_string();
    }
    // Headless: RL_SHOT=<out.png> RL_SECS=<n> renders the primary surface after n seconds (no window).
    let secs: f64 = env::var("RL_SECS").ok().and_then(|v| v.parse().ok()).unwrap_or(f64::INFINITY);
    let shot = env::var("RL_SHOT").ok();
    let headless = shot.is_some() || env::var_os("RL_HEADLESS").is_some() || env::var_os("RL_SCRIPT").is_some();
    let mut fe = if headless {
        None
    } else {
        match frontend::Frontend::new(1, m.uc.get_data().mixer.clone()) {
            Ok(f) => Some(f),
            Err(e) => {
                eprintln!("error: cannot open a window: {e}");
                return ExitCode::FAILURE;
            }
        }
    };
    let script = env::var("RL_SCRIPT").map(|s| parse_script(&s)).unwrap_or_default();
    let mut script = script.into_iter().peekable();
    m.uc.get_data_mut().skip_movies = skip_intro;
    // `--new-game`: once the main menu is up (first frame after the movies), click Novo jogo, the
    // first campaign and the first mission. Times are relative to that first frame.
    let mut auto: std::collections::VecDeque<Step> = if new_game {
        let mut script = String::from("1.0:move:400,296;1.5:click:400,296;3:move:400,321;3.5:click:400,321;6:move:400,296;6.5:click:400,296");
        if let Some(n) = mission.filter(|&n| n > 1) {
            // The game loads mission `counter + 1` after a victory: set the counter, win mission 1 with a full
            // stockpile, then click through the debriefing and the briefing.
            script += &format!(";40:dbg:poke 496fe4 {} 1;40.5:dbg:res all 500", n - 1);
            for k in 0..8 {
                script += &format!(";{}:click:400,300", 46 + k * 6);
            }
            script += ";100:click:305,525";
        }
        parse_script(&script).into()
    } else {
        Default::default()
    };
    let mut auto_t0: Option<std::time::Instant> = None;
    let start = std::time::Instant::now();
    let mut activated = fe.is_some();
    loop {
        if !activated && !m.uc.get_data().windows.is_empty() {
            activated = true;
            frontend::activate(&mut m.uc);
        }
        while script.peek().is_some_and(|s| s.at <= start.elapsed().as_secs_f64()) {
            let st = script.next().unwrap();
            if !run_script_step(&mut m, &st) {
                return ExitCode::SUCCESS;
            }
        }
        if !auto.is_empty() {
            if auto_t0.is_none() && m.uc.get_data().com.frames_presented > 60 {
                auto_t0 = Some(std::time::Instant::now());
            }
            if let Some(t0) = auto_t0 {
                while auto.front().is_some_and(|s| s.at <= t0.elapsed().as_secs_f64()) {
                    let st = auto.pop_front().unwrap();
                    run_script_step(&mut m, &st);
                }
            }
        }
        video_tick(&mut m);
        if let Some(h) = m.uc.get_data_mut().ui.submitted_host.take() {
            let _ = std::fs::create_dir_all(userdir());
            let _ = std::fs::write(userdir().join("lasthost.txt"), &h);
            m.uc.get_data_mut().com.dplay.get_or_insert_with(dplay::Dp::new).net.add_host(&h);
        }
        match m.step(0) {
            Ok(Some(code)) => {
                eprintln!("guest exited with {code}");
                return ExitCode::SUCCESS;
            }
            Ok(None) => {}
            Err(e) => {
                eprintln!("error: {e}");
                dump(&mut m, shot.as_deref());
                return ExitCode::FAILURE;
            }
        }
        if let Some(fe) = fe.as_mut() {
            if !fe.pump(&mut m.uc) {
                return ExitCode::SUCCESS;
            }
            fe.present(&mut m.uc);
        }
        if start.elapsed().as_secs_f64() >= secs {
            dump(&mut m, shot.as_deref());
            let mut c: Vec<_> = m.uc.get_data().api_counts.iter().map(|(k, v)| (*v, k.clone())).collect();
            c.sort();
            c.reverse();
            eprintln!("top calls: {:?}", &c[..c.len().min(12)]);
            return ExitCode::SUCCESS;
        }
    }
}

fn dump(m: &mut machine::Machine, shot: Option<&str>) {
    let Some(path) = shot else { return };
    let video = m.uc.get_data().video.as_ref().map(|v| (v.avi.width as u32, v.avi.height as u32, v.dec.rgb.chunks(3).flat_map(|p| [p[0], p[1], p[2], 255]).collect::<Vec<u8>>()));
    match video.or_else(|| com::snapshot(&mut m.uc)) {
        Some((w, h, rgba)) => {
            let f = std::fs::File::create(path).expect("create png");
            let mut enc = png::Encoder::new(std::io::BufWriter::new(f), w, h);
            enc.set_color(png::ColorType::Rgba);
            enc.set_depth(png::BitDepth::Eight);
            enc.write_header().and_then(|mut w| w.write_image_data(&rgba)).expect("write png");
            eprintln!("wrote {path} ({w}x{h}), {} frames presented", m.uc.get_data().com.frames_presented);
        }
        None => eprintln!("no primary surface to dump"),
    }
}

/// Advances the movie that is playing, if any, and ends its audio when it is done.
fn video_tick(m: &mut machine::Machine) {
    let st = m.uc.get_data_mut();
    let Some(v) = st.video.as_mut() else { return };
    v.tick();
}

#[cfg(test)]
mod tests {
    use super::*;
    use machine::testing::machine;

    fn step(cmd: &str, arg: &str) -> Step {
        Step { at: 0.0, cmd: cmd.into(), arg: arg.into() }
    }

    #[test]
    fn script_parsing_orders_steps_and_adds_release_events() {
        let v = parse_script("2:click:10,20; 0.5:move:1,2;3:key:13;4:rclick:5,6;5:dclick:7,8;bogus;x:move:1,1;6:quit");
        let got: Vec<_> = v.iter().map(|s| (s.at, s.cmd.as_str(), s.arg.as_str())).collect();
        assert_eq!(
            got,
            [
                (0.5, "move", "1,2"),
                (2.0, "click", "10,20"),
                (2.25, "up", "10,20"),
                (3.0, "key", "13"),
                (3.2, "keyup", "13"),
                (4.0, "rclick", "5,6"),
                (4.25, "rup", "5,6"),
                (5.0, "dclick", "7,8"),
                (5.25, "dup", "7,8"),
                (6.0, "quit", ""),
            ]
        );
        assert!(parse_script("").is_empty());
        // Arguments may contain colons (`dbg poke 496fe4 3 1`).
        assert_eq!(parse_script("1:dbg:res all 5")[0].arg, "res all 5");
    }

    #[test]
    fn coordinate_parsing_is_forgiving() {
        assert_eq!(xy("400, 296"), (400, 296));
        assert_eq!(xy("x,y"), (0, 0));
        assert_eq!(xy("12"), (0, 0));
        assert_eq!(xy("-5,7"), (-5, 7));
    }

    #[test]
    fn script_steps_drive_the_guest_input_queue() {
        let mut m = machine(&[0xeb, 0xfe], &[]);
        assert!(run_script_step(&mut m, &step("move", "10,20")));
        assert_eq!(m.uc.get_data().cursor, (10, 20));
        assert!(run_script_step(&mut m, &step("click", "30,40")));
        let msgs: Vec<_> = m.uc.get_data().msgs.iter().map(|x| x.message).collect();
        assert_eq!(msgs, [0x200, 0x200, 0x201]);
        assert!(m.uc.get_data().keys[1]);
        // `parse_script` names the release events "up" / "rup" / "dup" (the click name minus "click").
        run_script_step(&mut m, &step("up", "30,40"));
        assert!(!m.uc.get_data().keys[1]);
        run_script_step(&mut m, &step("rclick", "1,1"));
        assert!(m.uc.get_data().keys[2]);
        run_script_step(&mut m, &step("rup", "1,1"));
        assert!(!m.uc.get_data().keys[2]);
        run_script_step(&mut m, &step("dclick", "1,1"));
        assert_eq!(m.uc.get_data().msgs.back().unwrap().message, 0x203);
        m.uc.get_data_mut().msgs.clear();
        run_script_step(&mut m, &step("key", "27"));
        run_script_step(&mut m, &step("keyup", " 27 "));
        let msgs: Vec<_> = m.uc.get_data().msgs.iter().map(|x| (x.message, x.wparam)).collect();
        assert_eq!(msgs, [(0x100, 27), (0x102, 27), (0x101, 27)]);
        assert!(!m.uc.get_data().keys[27]);
        // Diagnostics and the debug console run against guest memory.
        wr_bytes_for_test(&mut m, 0x40_3000, &[1, 2, 3, 4]);
        assert!(run_script_step(&mut m, &step("mem", "403000:4")));
        machine::wr32(&mut m.uc, 0x4e19a0, 0x60_0000);
        machine::wr_bytes(&mut m.uc, 0x60_0000 + 0x114 * 3 + 2, &[7]);
        assert!(run_script_step(&mut m, &step("bld", "")));
        assert!(run_script_step(&mut m, &step("dbg", "poke 403010 77 1")));
        assert_eq!(machine::rd_bytes(&m.uc, 0x40_3010, 1), [77]);
        assert!(run_script_step(&mut m, &step("shot", "")), "no primary surface: nothing written, script goes on");
        assert!(run_script_step(&mut m, &step("frobnicate", "")));
        assert!(!run_script_step(&mut m, &step("quit", "")));
    }

    fn wr_bytes_for_test(m: &mut machine::Machine, a: u32, b: &[u8]) {
        machine::wr_bytes(&mut m.uc, a, b);
    }

    #[test]
    fn user_directory_prefers_the_override() {
        std::env::set_var("RL_USERDIR", "/tmp/rl-custom-userdir");
        assert_eq!(userdir(), PathBuf::from("/tmp/rl-custom-userdir"));
        std::env::remove_var("RL_USERDIR");
        assert!(userdir().ends_with("rising-lands"));
    }

    #[test]
    fn screenshot_of_the_primary_surface_is_a_png() {
        let mut m = machine(&[0xeb, 0xfe], &[]);
        let dir = std::env::temp_dir().join(format!("rl-shot-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let png_path = dir.join("shot.png");
        dump(&mut m, None);
        dump(&mut m, Some(png_path.to_str().unwrap()));
        assert!(!png_path.exists(), "no surface yet");
        // A 2x1 primary surface with a palette.
        let uc = &mut m.uc;
        let mem = uc.get_data_mut().alloc(2);
        machine::wr_bytes(uc, mem, &[0, 0]);
        uc.get_data_mut().com.objs.insert(0x100, com::Obj::Surface(com::Surface { w: 2, h: 1, mem, palette: None, back: None, key: None }));
        uc.get_data_mut().com.primary = Some(0x100);
        dump(&mut m, Some(png_path.to_str().unwrap()));
        let dec = png::Decoder::new(std::fs::File::open(&png_path).unwrap());
        let r = dec.read_info().unwrap();
        assert_eq!((r.info().width, r.info().height), (2, 1));
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn video_tick_advances_only_when_a_movie_plays() {
        let mut m = machine(&[0xeb, 0xfe], &[]);
        video_tick(&mut m);
        let avi = video::Avi::parse(b"RIFF\0\0\0\0AVI ").unwrap();
        m.uc.get_data_mut().video = Some(video::Player::new(avi));
        video_tick(&mut m);
        assert!(!m.uc.get_data().video.as_ref().unwrap().dirty, "no frames to decode");
    }

    #[test]
    fn avi_dump_helper_writes_requested_frames() {
        let dir = std::env::temp_dir().join(format!("rl-avi-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let avi = dir.join("m.avi");
        std::fs::write(&avi, b"RIFF\0\0\0\0AVI ").unwrap();
        let args: Vec<String> = ["--avi", avi.to_str().unwrap(), dir.join("f").to_str().unwrap(), "0", "2"].map(String::from).to_vec();
        assert_eq!(dump_avi(&args), ExitCode::SUCCESS);
        std::fs::remove_dir_all(dir).unwrap();
    }
}
