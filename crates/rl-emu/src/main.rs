use std::{env, path::PathBuf, process::ExitCode};

/// One scripted action: `seconds:command[:args]`, separated by `;` in `RL_SCRIPT`.
/// Commands: `move x,y`, `click x,y`, `rclick x,y`, `key vk`, `shot path`, `quit`.
struct Step {
    at: f64,
    cmd: String,
    arg: String,
}

fn parse_script(s: &str) -> Vec<Step> {
    let mut v: Vec<Step> = s
        .split(';')
        .filter_map(|item| {
            let mut p = item.trim().splitn(3, ':');
            Some(Step { at: p.next()?.parse().ok()?, cmd: p.next()?.to_string(), arg: p.next().unwrap_or("").to_string() })
        })
        .collect();
    // Clicks and key presses are held for a while: the game polls button state per frame.
    let mut extra = Vec::new();
    for st in &v {
        match st.cmd.as_str() {
            "click" | "rclick" => extra.push(Step { at: st.at + 0.25, cmd: format!("{}up", &st.cmd[..st.cmd.len() - 5]), arg: st.arg.clone() }),
            "key" => extra.push(Step { at: st.at + 0.2, cmd: "keyup".into(), arg: st.arg.clone() }),
            _ => {}
        }
    }
    v.extend(extra);
    v.sort_by(|a, b| a.at.total_cmp(&b.at));
    v
}

fn xy(arg: &str) -> (i32, i32) {
    let (x, y) = arg.split_once(',').unwrap_or(("0", "0"));
    (x.trim().parse().unwrap_or(0), y.trim().parse().unwrap_or(0))
}

fn run_script_step(m: &mut machine::Machine, st: &Step) -> bool {
    let uc = &mut m.uc;
    match st.cmd.as_str() {
        "move" => {
            let (x, y) = xy(&st.arg);
            frontend::inject_mouse(uc, x, y, None);
        }
        "click" | "rclick" => {
            let (x, y) = xy(&st.arg);
            frontend::inject_mouse(uc, x, y, None);
            frontend::inject_mouse(uc, x, y, Some((st.cmd == "rclick", true)));
        }
        // The "up" halves are generated by `parse_script` (e.g. "clickup" is `click` + "up").
        c if c.ends_with("up") && c != "keyup" => {
            let (x, y) = xy(&st.arg);
            frontend::inject_mouse(uc, x, y, Some((c.starts_with('r'), false)));
        }
        "key" => {
            let vk: u8 = st.arg.trim().parse().unwrap_or(0);
            frontend::inject_key(uc, vk, true);
        }
        "keyup" => {
            let vk: u8 = st.arg.trim().parse().unwrap_or(0);
            frontend::inject_key(uc, vk, false);
        }
        "shot" => dump(m, Some(&st.arg)),
        "quit" => return false,
        other => eprintln!("script: unknown command {other}"),
    }
    true
}

/// Where saved games and other writable files live.
fn userdir() -> PathBuf {
    if let Some(d) = env::var_os("RL_USERDIR") {
        return PathBuf::from(d);
    }
    let home = |rel: &str| env::var_os("HOME").map(|h| PathBuf::from(h).join(rel));
    let base = if cfg!(windows) {
        env::var_os("APPDATA").map(PathBuf::from)
    } else if cfg!(target_os = "macos") {
        home("Library/Application Support")
    } else {
        env::var_os("XDG_DATA_HOME").map(PathBuf::from).or_else(|| home(".local/share"))
    };
    base.unwrap_or_else(|| PathBuf::from(".")).join("rising-lands")
}

/// Debug helper: `rl-emu --avi movie.avi out_prefix first count` writes decoded frames as PNGs.
fn dump_avi(args: &[String]) -> ExitCode {
    let bytes = std::fs::read(&args[1]).expect("read avi");
    let avi = video::Avi::parse(&bytes).expect("parse avi");
    eprintln!("{}x{} {} frames rate {:?} audio {} samples {}ch {}Hz", avi.width, avi.height, avi.frames.len(), avi.rate, avi.audio.len(), avi.channels, avi.sample_rate);
    let (first, count): (usize, usize) = (args[3].parse().unwrap_or(0), args[4].parse().unwrap_or(1));
    let mut dec = video::Cinepak::new(avi.width, avi.height);
    for (i, f) in avi.frames.iter().enumerate().take(first + count) {
        dec.decode(f).expect("decode");
        if i >= first {
            let file = std::fs::File::create(format!("{}{i:04}.png", args[2])).expect("png");
            let mut enc = png::Encoder::new(std::io::BufWriter::new(file), avi.width as u32, avi.height as u32);
            enc.set_color(png::ColorType::Rgb);
            enc.set_depth(png::BitDepth::Eight);
            enc.write_header().and_then(|mut w| w.write_image_data(&dec.rgb)).expect("write");
        }
    }
    ExitCode::SUCCESS
}

fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("--avi") && args.len() >= 5 {
        return dump_avi(&args);
    }
    let (Some(install), Some(disc)) = (args.first(), args.get(1)) else {
        eprintln!("usage: rl-emu <INSTALHD dir> <disc root dir>");
        return ExitCode::from(2);
    };
    let install = PathBuf::from(install);
    let disc = PathBuf::from(disc);
    let mut m = match machine::Machine::new(&install.join("RISING.EXE"), &install, &disc, &userdir()) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    };
    // Headless: RL_SHOT=<out.png> RL_SECS=<n> renders the primary surface after n seconds (no window).
    let secs: f64 = env::var("RL_SECS").ok().and_then(|v| v.parse().ok()).unwrap_or(f64::INFINITY);
    let shot = env::var("RL_SHOT").ok();
    let headless = shot.is_some() || env::var_os("RL_HEADLESS").is_some() || env::var_os("RL_SCRIPT").is_some();
    let mut fe = if headless {
        None
    } else {
        match frontend::Frontend::new(1, m.uc.get_data().mixer.clone()) {
            Ok(f) => Some(f),
            Err(e) => {
                eprintln!("error: cannot open a window: {e}");
                return ExitCode::FAILURE;
            }
        }
    };
    let script = env::var("RL_SCRIPT").map(|s| parse_script(&s)).unwrap_or_default();
    let mut script = script.into_iter().peekable();
    let start = std::time::Instant::now();
    let mut activated = fe.is_some();
    loop {
        if !activated && !m.uc.get_data().windows.is_empty() {
            activated = true;
            frontend::activate(&mut m.uc);
        }
        while script.peek().is_some_and(|s| s.at <= start.elapsed().as_secs_f64()) {
            let st = script.next().unwrap();
            if !run_script_step(&mut m, &st) {
                return ExitCode::SUCCESS;
            }
        }
        video_tick(&mut m);
        match m.step(8_000) {
            Ok(Some(code)) => {
                eprintln!("guest exited with {code}");
                return ExitCode::SUCCESS;
            }
            Ok(None) => {}
            Err(e) => {
                eprintln!("error: {e}");
                dump(&mut m, shot.as_deref());
                return ExitCode::FAILURE;
            }
        }
        if let Some(fe) = fe.as_mut() {
            if !fe.pump(&mut m.uc) {
                return ExitCode::SUCCESS;
            }
            fe.present(&mut m.uc);
        }
        if start.elapsed().as_secs_f64() >= secs {
            dump(&mut m, shot.as_deref());
            let mut c: Vec<_> = m.uc.get_data().api_counts.iter().map(|(k, v)| (*v, k.clone())).collect();
            c.sort();
            c.reverse();
            eprintln!("top calls: {:?}", &c[..c.len().min(12)]);
            return ExitCode::SUCCESS;
        }
    }
}

fn dump(m: &mut machine::Machine, shot: Option<&str>) {
    let Some(path) = shot else { return };
    let video = m.uc.get_data().video.as_ref().map(|v| (v.avi.width as u32, v.avi.height as u32, v.dec.rgb.chunks(3).flat_map(|p| [p[0], p[1], p[2], 255]).collect::<Vec<u8>>()));
    match video.or_else(|| com::snapshot(&mut m.uc)) {
        Some((w, h, rgba)) => {
            let f = std::fs::File::create(path).expect("create png");
            let mut enc = png::Encoder::new(std::io::BufWriter::new(f), w, h);
            enc.set_color(png::ColorType::Rgba);
            enc.set_depth(png::BitDepth::Eight);
            enc.write_header().and_then(|mut w| w.write_image_data(&rgba)).expect("write png");
            eprintln!("wrote {path} ({w}x{h}), {} frames presented", m.uc.get_data().com.frames_presented);
        }
        None => eprintln!("no primary surface to dump"),
    }
}

/// Advances the movie that is playing, if any, and ends its audio when it is done.
fn video_tick(m: &mut machine::Machine) {
    let st = m.uc.get_data_mut();
    let Some(v) = st.video.as_mut() else { return };
    v.tick();
}
